async def upsert_goods():
    """带 id 的记录按 id UPDATE 现有；不带 id 的按 name UPSERT。整体幂等。"""
    await Tortoise.init(config=TORTOISE_ORM)

    categories = await Category.all()
    print(f"目标分类数：{len(categories)}")
    print(f"待写入商品数：{len(GOODS)}")

    inserted = 0
    updated = 0
    img_counter = {}

    for entry in GOODS:
        cat_id = entry['cat']
        img_counter.setdefault(cat_id, 0)
        img_url = img_for(cat_id, img_counter[cat_id])
        img_counter[cat_id] += 1

        fields = dict(
            name=entry['name'],
            description=entry['desc'],
            detail=entry['detail'],
            ingredients=entry['ingredients'],
            specs=entry['specs'],
            shelf_life=entry['shelf'],
            weight=entry['weight'],
            origin=entry['origin'],
            serves=entry['serves'],
            img=img_url,
            price=entry['price'],
            num=entry['num'],
            unit='份',
            category_id=cat_id,
        )

        existing = None
        if entry.get('id'):
            existing = await Goods.filter(id=entry['id']).first()
        else:
            existing = await Goods.filter(name=entry['name']).first()

        if existing:
            for k, v in fields.items():
                setattr(existing, k, v)
            await existing.save()
            updated += 1
        else:
            await Goods.create(**fields)
            inserted += 1

    print(f"\n✅ 完成：新增 {inserted} 个，更新 {updated} 个")

    from tortoise.functions import Count
    stats = await Goods.annotate(count=Count('id')).group_by('category_id').values('category_id', 'count')
    print("\n各分类商品数：")
    for s in sorted(stats, key=lambda x: x['category_id']):
        cat = next((c.name for c in categories if c.id == s['category_id']), '?')
        flag = '✓' if s['count'] == 10 else '✗'
        print(f"  {flag} {cat}(id={s['category_id']}): {s['count']} 个")

    await Tortoise.close_connections()


if __name__ == '__main__':
    asyncio.run(upsert_goods())
